  (dataset) =>
  ([fdcId, name, kcal, protein, carbs, fat, keywords]) =>
    Object.freeze({
      id: `usda-${fdcId}`,
      name,
      kcal,
      protein,
      carbs,
      fat,
      keywords,
      baseAmount: 100,
      baseUnit: "g",
      source: `${dataset} · FDC ${fdcId}`,
      sourceUrl: `https://fdc.nal.usda.gov/food-details/${fdcId}/nutrients`,
    });

